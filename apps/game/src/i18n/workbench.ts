export const WORKBENCH_TRANSLATIONS = {
  'en-US': en,
  'pt-BR': ptBR,
  'zh-CN': zhCN,
  'fil-PH': filPH,
} as const satisfies Record<LocaleCode, WorkbenchDictionary>;

type InterpolationValues = Readonly<Record<string, string | number>>;

export function translateWorkbench(
  locale: LocaleCode | string,
  key: WorkbenchTranslationKey,
  values: InterpolationValues = {},
): string {
  const selected = isSupportedLocale(locale) ? WORKBENCH_TRANSLATIONS[locale] : en;
  const template = selected[key] ?? en[key];
  return template.replace(/\{([^}]+)\}/gu, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  );
}

export function applyWorkbenchTranslations(locale: LocaleCode, root: ParentNode = document): void {
  document.documentElement.lang = locale;
  document.title = translateWorkbench(locale, 'pageTitle');
  root.querySelectorAll<HTMLElement>('[data-workbench-i18n]').forEach((element) => {
    const key = element.dataset.workbenchI18n as WorkbenchTranslationKey | undefined;
    if (key) element.textContent = translateWorkbench(locale, key);
  });
  root.querySelectorAll<HTMLElement>('[data-workbench-i18n-aria-label]').forEach((element) => {
    const key = element.dataset.workbenchI18nAriaLabel as WorkbenchTranslationKey | undefined;
    if (key) element.setAttribute('aria-label', translateWorkbench(locale, key));
  });
  root.querySelectorAll<HTMLImageElement>('[data-workbench-i18n-alt]').forEach((element) => {
    const key = element.dataset.workbenchI18nAlt as WorkbenchTranslationKey | undefined;
    if (key) element.alt = translateWorkbench(locale, key);
  });
}
